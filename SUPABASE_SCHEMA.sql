-- Automatically provision every public signup as a student.
-- This avoids trusting a browser-side INSERT for profile creation and also
-- works when email confirmation is enabled (before the user has a session).
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  safe_name text;
begin
  safe_name := left(
    coalesce(
      nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''),
      'HostelCare User'
    ),
    100
  );

  insert into public.profiles (user_id, full_name, email, role)
  values (new.id, safe_name, left(coalesce(new.email, ''), 320), 'student')
  on conflict (user_id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

revoke execute on function public.handle_new_user() from public;

