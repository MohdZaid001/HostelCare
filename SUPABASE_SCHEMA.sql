create table if not exists profiles (
  id bigint generated by default as identity primary key,
  user_id uuid unique not null references auth.users(id) on delete cascade,
  full_name text not null,
  email text not null,
  role text not null check (role in ('student','worker')),
  created_at timestamptz default now()
);

create table if not exists complaints (
  id bigint generated by default as identity primary key,
  student_id uuid not null references auth.users(id) on delete cascade,
  worker_id uuid references auth.users(id) on delete set null,
  title text not null,
  description text not null,
  category text not null,
  location text not null,
  priority text not null default 'Medium' check (priority in ('Low','Medium','High')),
  status text not null default 'Pending' check (status in ('Pending','Assigned','In Progress','Resolved','Rejected')),
  resolution_notes text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

alter table complaints add column if not exists resolution_notes text;

create table if not exists feedback (
  id bigint generated by default as identity primary key,
  complaint_id bigint unique not null references complaints(id) on delete cascade,
  student_id uuid not null references auth.users(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  comment text,
  created_at timestamptz default now()
);

