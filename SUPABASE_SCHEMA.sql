-- Prevent a signed-in user from changing their own role through the browser.
create or replace function public.prevent_self_role_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() = old.user_id and new.role is distinct from old.role then
    raise exception 'Profile role cannot be changed by the account owner';
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_prevent_self_role_change on profiles;
create trigger profiles_prevent_self_role_change
before update on profiles
for each row execute function public.prevent_self_role_change();

revoke execute on function public.prevent_self_role_change() from public;

-- Cleanly recreate application policies.
drop policy if exists "profiles_select_own" on profiles;
drop policy if exists "profiles_insert_own" on profiles;
drop policy if exists "profiles_update_own" on profiles;
drop policy if exists "complaints_student_select" on complaints;
drop policy if exists "complaints_student_insert" on complaints;
drop policy if exists "complaints_worker_queue_select" on complaints;
drop policy if exists "feedback_student_select" on feedback;
drop policy if exists "feedback_student_insert" on feedback;

create policy "profiles_select_own"
on profiles for select to authenticated
using (auth.uid() = user_id);

-- IMPORTANT: browser self-registration can only create student profiles.
-- Worker profiles must be provisioned by a trusted/admin process.
create policy "profiles_insert_own"
on profiles for insert to authenticated
with check (
  auth.uid() = user_id
  and role = 'student'
);

create policy "profiles_update_own"
on profiles for update to authenticated
using (auth.uid() = user_id)
with check (
  auth.uid() = user_id
);

create policy "complaints_student_select"
on complaints for select to authenticated
using (
  auth.uid() = student_id
  and exists (
    select 1 from profiles p
    where p.user_id = auth.uid() and p.role = 'student'
  )
);

create policy "complaints_student_insert"
on complaints for insert to authenticated
with check (
  auth.uid() = student_id
  and exists (
    select 1 from profiles p
    where p.user_id = auth.uid() and p.role = 'student'
  )
);

-- Workers can see only:
--   * their own assigned complaints, OR
--   * the unassigned Pending queue.
create policy "complaints_worker_queue_select"
on complaints for select to authenticated
using (
  auth.uid() = worker_id
  or (
    worker_id is null
    and status = 'Pending'
    and exists (
      select 1 from profiles p
      where p.user_id = auth.uid() and p.role = 'worker'
    )
  )
);

-- No direct UPDATE policy is granted to workers. Status changes must use the
-- authorized update_complaint_status() RPC below.
create policy "feedback_student_select"
on feedback for select to authenticated
using (
  auth.uid() = student_id
  and exists (
    select 1 from complaints c
    where c.id = complaint_id
      and c.student_id = auth.uid()
  )
);

create policy "feedback_student_insert"
on feedback for insert to authenticated
with check (
  auth.uid() = student_id
  and exists (
    select 1 from profiles p
    where p.user_id = auth.uid() and p.role = 'student'
  )
  and exists (
    select 1 from complaints c
    where c.id = complaint_id
      and c.student_id = auth.uid()
      and c.status = 'Resolved'
  )
);

-- Atomic "Take Complaint" operation.
create or replace function public.take_complaint(p_complaint_id bigint)
returns complaints
language plpgsql
security definer
set search_path = public
as $$
declare
  result_row complaints;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if not exists (
    select 1 from profiles
    where user_id = auth.uid() and role = 'worker'
  ) then
    raise exception 'Only workers can take complaints';
  end if;

  update complaints
  set worker_id = auth.uid(),
      status = 'Assigned',
      updated_at = now()
  where id = p_complaint_id
    and worker_id is null
    and status = 'Pending'
  returning * into result_row;

  if result_row.id is null then
    raise exception 'Complaint is already assigned or no longer pending';
  end if;

  return result_row;
end;
$$;

revoke execute on function public.take_complaint(bigint) from public;
grant execute on function public.take_complaint(bigint) to authenticated;

-- Secure worker status update.
-- Allowed transitions:
--   Assigned -> Assigned (edit notes)
--   Assigned -> In Progress
--   Assigned -> Rejected
--   In Progress -> In Progress (edit notes)
--   In Progress -> Resolved
--   In Progress -> Rejected
--   Resolved -> Resolved (edit notes)
--   Rejected -> Rejected (edit notes)
--
-- Pending is intentionally NOT editable here; it must first be claimed by
-- take_complaint(). This prevents a worker from changing an unassigned item.
create or replace function public.update_complaint_status(
  p_complaint_id bigint,
  p_status text,
  p_resolution_notes text default null
)
returns complaints
language plpgsql
security definer
set search_path = public
as $$
declare
  current_row complaints;
  result_row complaints;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if not exists (
    select 1 from profiles
    where user_id = auth.uid() and role = 'worker'
  ) then
    raise exception 'Only workers can update complaints';
  end if;

  if p_status not in ('Assigned', 'In Progress', 'Resolved', 'Rejected') then
    raise exception 'Invalid complaint status';
  end if;

  if p_resolution_notes is not null and length(p_resolution_notes) > 2000 then
    raise exception 'Resolution notes must be 2000 characters or less';
  end if;

  select * into current_row
  from complaints
  where id = p_complaint_id
    and worker_id = auth.uid()
  for update;

  if current_row.id is null then
    raise exception 'Complaint is not assigned to this worker';
  end if;

  if current_row.status <> p_status then
    if not (
      (current_row.status = 'Assigned' and p_status in ('In Progress', 'Rejected'))
      or
      (current_row.status = 'In Progress' and p_status in ('Resolved', 'Rejected'))
    ) then
      raise exception 'Invalid status transition from % to %', current_row.status, p_status;
    end if;
  end if;

  update complaints
  set status = p_status,
      resolution_notes = nullif(trim(p_resolution_notes), ''),
      updated_at = now()
  where id = p_complaint_id
    and worker_id = auth.uid()
  returning * into result_row;

  return result_row;
end;
$$;

revoke execute on function public.update_complaint_status(bigint, text, text) from public;
grant execute on function public.update_complaint_status(bigint, text, text) to authenticated;

